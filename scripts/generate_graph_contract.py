"""Generate Pi's read-only parameter schemas and fixed prompt from Python contracts."""

import json
from pathlib import Path

from agent_workbench.contracts.graph_prompt import SHARED_GRAPH_PROMPT
from agent_workbench.contracts.graph_read import GraphQuery, GraphRead


def generated() -> str:
    read = GraphRead.model_json_schema()
    # Inline the query schema; Pi tools do not need transport identity fields.
    read.pop("$defs", None)
    read["properties"]["query"] = GraphQuery.model_json_schema()
    return ("// Generated by scripts/generate_graph_contract.py; do not edit.\n"
            + "export const SHARED_GRAPH_PROMPT = " + json.dumps(SHARED_GRAPH_PROMPT, ensure_ascii=False) + ";\n"
            + "export const GRAPH_READ_SCHEMA = " + json.dumps(read, ensure_ascii=False) + ";\n")


if __name__ == "__main__":
    Path("worker/src/graph-contract.ts").write_text(generated(), encoding="utf-8")
